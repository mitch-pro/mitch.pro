import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const base = process.env.SITE_AUDIT_BASE_URL || 'http://127.0.0.1:4320';
assert(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Run this test against an isolated local server.');
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', serviceWorkers: 'block' });
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/');
  await page.waitForFunction(() => window.MitchShell?.ready);
  assert(await page.locator('#backbtn').isHidden(), 'Frame back button must stay hidden until a game opens.');
  assert.equal(await page.locator('.home-section-heading').first().innerText(), 'Shortcuts');
  assert.equal(await page.locator('.feature-eyebrow, .home-hero-kicker').count(), 0);
  assert.equal(await page.locator('#_agree_footer').evaluate(el => getComputedStyle(el).position), 'static');
  await page.evaluate(() => localStorage.setItem('_prefDisplay', JSON.stringify({ gameLaunch: 'iframe' })));
  await page.locator('.home-actions a[href="/preferences/"]').click();
  await page.waitForURL(base + '/preferences/');
  assert.equal(await page.locator('iframe#fullframe').count(), 0, 'Account pages must navigate normally even when games use frames.');
  const account = page.locator('#account h2');
  await account.focus();
  await page.keyboard.press('Enter');
  assert.equal(await account.getAttribute('aria-expanded'), 'true');
  await page.keyboard.press('Space');
  assert.equal(await account.getAttribute('aria-expanded'), 'false');
  await page.selectOption('#densitySelect', 'huge');
  assert.equal(await page.locator('html').evaluate(el => getComputedStyle(el).fontSize), '17.6px');
  await page.selectOption('#radiusSelect', 'round');
  assert.equal(await page.locator('#appearance').evaluate(el => getComputedStyle(el).borderRadius), '14px');
  await page.selectOption('#fontSelect', 'mono');
  assert((await page.locator('body').evaluate(el => getComputedStyle(el).fontFamily)).includes('monospace'));
  await page.selectOption('#motionSelect', 'off');
  assert(await page.locator('html').evaluate(el => el.classList.contains('theme-no-motion')));
  await page.selectOption('#materialSelect', 'glass');
  assert.equal(await page.locator('html').getAttribute('data-material'), 'glass');
  for (const [id, value] of [['densitySelect', 'normal'], ['radiusSelect', 'soft'], ['fontSelect', 'system'], ['motionSelect', 'on'], ['materialSelect', 'auto']]) await page.selectOption('#' + id, value);
  await page.evaluate(() => window.__siteTheme.setMode('light'));
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  assert.equal(await page.locator('meta[name="theme-color"]').getAttribute('content'), '#f6f7f3');
  await page.evaluate(() => window.__siteTheme.setAccent('#ffffff'));
  assert.equal(await page.locator('html').evaluate(el => el.style.getPropertyValue('--t-ac-ink')), '#000000');
  await page.evaluate(() => window.__siteTheme.setAccent('#000000'));
  assert.equal(await page.locator('html').evaluate(el => el.style.getPropertyValue('--t-ac-ink')), '#ffffff');
  await page.evaluate(() => window.__siteTheme.setAccent(''));
  const light = await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor);
  await page.goto(base + '/');
  assert.equal(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor), light, 'Homepage and account pages must share the theme.');
  await page.evaluate(() => window.__siteTheme.setMode('dark'));
  await page.locator('.home-feature[href="/game-portal/"]').click();
  await page.waitForURL(base + '/game-portal/');
  assert(await page.locator('#player').isHidden(), 'Opening the games library must not open a nested player.');
  await page.goto(base + '/shop/');
  await page.locator('#market .card').first().waitFor();
  await page.locator('#shop-search').fill('no such item qqqqqq');
  assert.equal(await page.locator('#market .card:visible').count(), 0);
  await page.locator('#shop-search').fill('');
  assert(await page.locator('#market .card:visible').count() > 0);
  await page.goto(base + '/rjuhsd/?school=oakmont');
  await page.waitForFunction(() => document.body.dataset.school === 'oakmont');
  await page.selectOption('#school-select', 'roseville');
  assert.equal(new URL(page.url()).pathname, '/rjuhsd/');
  assert.equal(new URL(page.url()).searchParams.get('school'), 'roseville');
  await page.reload();
  await page.waitForFunction(() => document.body.dataset.school === 'roseville');
  await page.locator('[data-switch-school="antelope"]').first().click();
  await page.waitForFunction(() => document.body.dataset.school === 'antelope');
  assert.equal(new URL(page.url()).pathname, '/rjuhsd/');
  await page.goto(base + '/');
  await page.setViewportSize({ width: 390, height: 844 });
  const more = page.locator('#mobile-dock button');
  await more.click();
  assert.equal(await more.getAttribute('aria-expanded'), 'true');
  assert(await page.locator('#mobile-menu').evaluate(el => el.open));
  assert.equal(await page.locator('#mobile-menu a').filter({ hasText: 'BeatDash' }).getAttribute('href'), 'https://beatdash.win/');
  await page.getByRole('button', { name: 'Close menu', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#mobile-dock button').getAttribute('aria-expanded') === 'false');
  for (const path of ['/', '/preferences/', '/shop/', '/marketplace/', '/leaderboard/', '/rjuhsd/', '/tor/']) {
    await page.goto(base + path);
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 844 });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${path} overflows at ${width}px`);
      assert(await page.locator('[hidden]').evaluateAll(elements => elements.every(el => getComputedStyle(el).display === 'none')), `${path} exposes hidden controls`);
    }
  }
  await page.goto(base + '/enroll/');
  assert.equal(await page.locator('.mitch-wallet, #site-topbar, #mobile-dock').count(), 0, 'Account access must not mount an extra account toolbar.');
  assert.deepEqual(errors, []);
  console.log('PASS: native page navigation, game frame preferences, hidden controls, keyboard settings, theme persistence, shop search, school switching/reload, and mobile navigation.');
} finally { await browser.close(); }
